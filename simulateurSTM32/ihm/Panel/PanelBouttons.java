    private void jButtonOneStepActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonOneStepActionPerformed

        
       for(EtatPipeline ep : ihm.LCM3simulator.thePipe.getEtat()) {
           System.out.println("État du pipeline: " + formatPipelineAddress(ep.getFetchPC()));
       }
       
       valeurPrt = ihm.LCM3simulator.thePipe.getEtat()[0].getFetchPC();
       System.out.println("Adresse courante du pipeline: " + formatPipelineAddress(valeurPrt));
       if (valeurPrt==-1){
           ligneSelectionne= 0;
           valeurPct=ligneSelectionne;
       }
       else if ( valeurPrt > valeurPct )
          {valeurPct=valeurPrt;
              ligneSelectionne = valeurPrt - DECODE_OFFSET - cptASupp2;
      
       }
       else if (valeurPrt < valeurPct )
        {
           cptASupp2=1;
            ligneSelectionne = valeurPrt - ROM_BASE_ADDRESS;  // Calcul de l'offset relatif dans la ROM
            valeurPct=ligneSelectionne;
        }

        if(cptASupp -2 >= 0) {
            ihm.panelMemoires.selectionnerLigne(cptASupp - 2, mesCouleurs[(cptASupp - 2) % 8]);
            cptASupp++;
            cptASupp2++;
        }
        
        if(ihm.enSim==Ihm.ENOK){
            ihm.LCM3simulator.oneStep();
            ihm.panelRAM.aff(ihm.LCM3simulator);
            ihm.panelPipeline.disp(ihm.LCM3simulator.thePipe);
            if (ihm.panelAnim != null) {
                ihm.panelAnim.disp(ihm.LCM3simulator.thePipe);
            }
            ihm.panelFlags.affFlags(ihm.LCM3simulator.getFlagN(),
                    ihm.LCM3simulator.getFlagZ(), ihm.LCM3simulator.getFlagV()
                    , ihm.LCM3simulator.getFlagC());
            for(Modification m : ihm.LCM3simulator.modifs.getCurModifs()){
                if(m.getType()==Modification.REG){
                    ihm.panelRegistres.setModifReg(m.getLoc(),m.getVal());
                }
                else
                if(m.getType()==Modification.PC){
                    ihm.panelRegistres.setModifPC(m.getVal());
                }
                else
                if(m.getType()==Modification.RAM){
                    ihm.panelRAM.affRouge(m.getLoc(), m.getVal());
                    ihm.panelRegistres.setModifPC(m.getVal());
                }

            }
             
            ihm.LCM3simulator.modifs.next();
              
            
            
        }

    }//GEN-LAST:event_jButtonOneStepActionPerformed

