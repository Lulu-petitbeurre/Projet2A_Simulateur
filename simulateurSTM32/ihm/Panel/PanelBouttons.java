    // Adresse de base de la mémoire ROM du STM32
    private static final int ROM_BASE_ADDRESS = 0x08000000;  // 134217728 en décimal
    
    // Constantes pour le pipeline
    private static final int INSTRUCTION_SIZE = 2;           // Taille d'une instruction en octets
    private static final int FETCH_OFFSET = ROM_BASE_ADDRESS;                    // 0x08000000 (134217728)
    private static final int DECODE_OFFSET = ROM_BASE_ADDRESS + INSTRUCTION_SIZE; // 0x08000002 (134217730)
    private static final int EXECUTE_OFFSET = ROM_BASE_ADDRESS + (INSTRUCTION_SIZE * 3); // 0x08000006 (134217734)
    private static final int PIPELINE_STEP = 5;             // Incrément pour les étapes du pipeline
    
    // Méthode utilitaire pour formater l'affichage d'une adresse du pipeline
    private String formatPipelineAddress(int address) {
        if (address == -1) {
            return "Pipeline vide";
        }
        String stage = "";
        String hex = String.format("0x%08X", address);
        
        if (address == FETCH_OFFSET) {
            stage = "Fetch";
        } else if (address == DECODE_OFFSET) {
            stage = "Decode";
        } else if (address == EXECUTE_OFFSET) {
            stage = "Execute";
        }
        
        return String.format("%s (Étape: %s, Adresse: %s)", 
            stage, 
            stage.isEmpty() ? "Inconnue" : stage, 
            hex);
    }
    
